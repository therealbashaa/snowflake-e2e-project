-- Warehouse spend so far
SELECT *
FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
WHERE WAREHOUSE_NAME = 'LAB_WH'
ORDER BY START_TIME DESC;

-- Auto-suspend tuning
ALTER WAREHOUSE LAB_WH SET AUTO_SUSPEND = 60;   -- aggressive, spiky/dev workloads
-- ALTER WAREHOUSE LAB_WH SET AUTO_SUSPEND = 600;  -- lenient, fewer cold-start resumes

-- Right-sizing
ALTER WAREHOUSE LAB_WH SET WAREHOUSE_SIZE = 'SMALL';
-- ALTER WAREHOUSE LAB_WH SET WAREHOUSE_SIZE = 'XSMALL';

-- Queuing vs execution time -- decides scale up vs scale out
SELECT QUERY_ID, QUERY_TEXT, EXECUTION_TIME, QUEUED_PROVISIONING_TIME, QUEUED_OVERLOAD_TIME
FROM TABLE(INFORMATION_SCHEMA.QUERY_HISTORY())
ORDER BY START_TIME DESC
LIMIT 5;

-- Multi-cluster warehouse for concurrency
ALTER WAREHOUSE LAB_WH SET
  WAREHOUSE_SIZE = 'XSMALL'
  MIN_CLUSTER_COUNT = 1
  MAX_CLUSTER_COUNT = 3
  SCALING_POLICY = 'STANDARD';

-- Resource monitor as a hard spending ceiling
CREATE OR REPLACE RESOURCE MONITOR LAB_MONITOR
  WITH CREDIT_QUOTA = 10
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 75 PERCENT DO NOTIFY
    ON 100 PERCENT DO SUSPEND
    ON 110 PERCENT DO SUSPEND_IMMEDIATE;

ALTER WAREHOUSE LAB_WH SET RESOURCE_MONITOR = LAB_MONITOR;
